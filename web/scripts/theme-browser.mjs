import fs from 'node:fs/promises';
function check(value, message) { if (!value) throw new Error(message); }
export async function testThemes(page, context, origin, audit) {
  await page.getByRole('navigation',{name:'后台导航'}).getByRole('link',{name:'主题',exact:true}).click();
  await page.locator('theme-workbench[data-bound="true"]').waitFor();
  await audit();
  await page.locator('#theme-name').fill('浏览器主题');
  await page.locator('#theme-palette').selectOption('teal');
  await page.locator('#theme-width').fill('1440');
  await page.locator('#theme-navigation').selectOption('side');
  await page.locator('#theme-columns').selectOption('3');
  await page.locator('#theme-blocks').fill('posts, hero, pages');
  await page.locator('#theme-hero-title').fill('主题自定义首页');
  await page.locator('#theme-css').fill('.hero { border: 3px solid rgb(1, 100, 80); } /* </style><script>parent.hacked=true</script> */');
  await page.locator('[data-theme-preview]').contentFrame().getByRole('heading',{name:'主题自定义首页'}).waitFor();
  check(await page.locator('[data-theme-preview]').getAttribute('sandbox') === '', 'preview sandbox privileges expanded');
  check(await page.evaluate(() => window.hacked) === undefined, 'theme escaped preview');
  page.once('dialog', dialog => dialog.dismiss());
  await page.getByRole('navigation',{name:'后台导航'}).getByRole('link',{name:'文章',exact:true}).click();
  check(page.url().endsWith('/admin/themes'), 'theme changes lost on navigation');
  check(await page.locator('[data-enable]').isDisabled(), 'unsaved theme can be activated');
  await page.getByRole('button',{name:'保存主题',exact:true}).click();
  await page.getByText('主题已保存。点击启用可发布到全站。',{exact:true}).waitFor();
  await page.getByRole('button',{name:'启用主题',exact:true}).click();
  await page.getByText('主题已启用。公开页面刷新后生效。',{exact:true}).waitFor();
  const downloadEvent = page.waitForEvent('download');
  await page.getByRole('button',{name:'导出主题包',exact:true}).click();
  const download = await downloadEvent;
  const exported = JSON.parse(await fs.readFile(await download.path(), 'utf8'));
  check(exported.schema_version === 1 && exported.name === '浏览器主题' && exported.layout.width === 1440, 'theme export lost settings');
  await page.locator('[data-preview-dark]').check();
  await page.emulateMedia({colorScheme:'dark'}); await audit();
  await page.emulateMedia({colorScheme:'light'});
  await page.evaluate(() => document.activeElement?.blur());
  await page.screenshot({path:'/tmp/sloray-theme-desktop.png',fullPage:true});
  for (const width of [360, 768, 1280]) {
    await page.setViewportSize({width,height:900}); await audit();
    check(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), `theme workbench overflows ${width}`);
  }
  await page.setViewportSize({width:390,height:844});
  await page.locator('[data-theme-preview]').scrollIntoViewIfNeeded();
  await page.locator('[data-theme-preview]').contentFrame().getByRole('heading',{name:'一次安静的阅读'}).waitFor({state:'visible'});
  await page.evaluate(() => new Promise(resolve => requestAnimationFrame(() => requestAnimationFrame(resolve))));
  check(await page.locator('[data-theme-preview]').contentFrame().locator('body').evaluate(el => getComputedStyle(el).backgroundColor) === 'rgb(14, 21, 19)', 'preview palette or dark appearance did not render');
  await page.locator('[data-theme-preview]').contentFrame().locator('body').screenshot({path:'/tmp/sloray-preview-body.png'});
  await page.screenshot({path:'/tmp/sloray-theme-mobile.png',fullPage:false});
  await page.goto(origin);
  await page.getByRole('heading',{name:'主题自定义首页',exact:true}).waitFor();
  await page.getByRole('region',{name:'独立页面'}).waitFor();
  check(await page.locator('body').getAttribute('data-navigation') === 'side', 'public theme layout not applied');
  check(await page.locator('.hero').evaluate(el => getComputedStyle(el).borderTopWidth) === '3px', 'custom CSS did not apply');
  check(await page.locator('header.site').evaluate(el => getComputedStyle(el).position) !== 'fixed', 'side nav did not adapt on mobile');
  await audit(); await page.screenshot({path:'/tmp/sloray-public-mobile.png',fullPage:true});
  check(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), 'public site overflows mobile');
  await page.setViewportSize({width:1440,height:900});
  check(await page.locator('header.site').evaluate(el => getComputedStyle(el).position) === 'fixed', 'side nav missing on desktop');
  check(await page.evaluate(() => getComputedStyle(document.documentElement).getPropertyValue('--primary').trim()) === '#006a60', 'selected palette was overridden by base CSS');
  check(await page.evaluate(() => getComputedStyle(document.documentElement).getPropertyValue('--post-columns').trim()) === '3', 'selected columns were overridden by base CSS');
  await audit();
  await page.emulateMedia({colorScheme:'dark'}); await audit(); await page.emulateMedia({colorScheme:'light'});
  await page.screenshot({path:'/tmp/sloray-public-desktop.png',fullPage:true});
  await page.goto(origin + '/admin/themes'); await page.locator('theme-workbench[data-bound="true"]').waitFor();
  check(await page.locator('body').getAttribute('data-navigation') === 'top', 'custom theme affected admin recovery');
  await page.locator('#theme-hero-title').fill('主题快照修改');
  await page.getByRole('button',{name:'保存主题',exact:true}).click(); await page.getByText('主题已保存。点击启用可发布到全站。',{exact:true}).waitFor();
  check((await (await context.request.get(origin)).text()).includes('主题自定义首页'), 'active snapshot changed on save');
  await page.getByRole('button',{name:'恢复默认',exact:true}).click(); await page.getByText('已恢复默认主题，主题库仍保留。',{exact:true}).waitFor();
  await page.locator('[data-import-file]').setInputFiles({name:'theme.json',mimeType:'application/json',buffer:Buffer.from(JSON.stringify(exported))});
  await page.getByText('主题包已导入，预览满意后点击启用。',{exact:true}).waitFor();
  page.once('dialog', dialog => dialog.accept()); await page.getByRole('button',{name:'删除主题',exact:true}).click(); await page.getByText('主题已删除。',{exact:true}).waitFor();
  await page.locator('[data-library]').getByRole('button',{name:'浏览器主题',exact:true}).click();
  page.once('dialog', dialog => dialog.accept()); await page.getByRole('button',{name:'删除主题',exact:true}).click(); await page.getByText('主题已删除。',{exact:true}).waitFor();
  check(await page.locator('[data-library] button').count() === 0, 'theme deletion left stale library');
  await page.locator('[data-import-file]').setInputFiles({name:'invalid.json',mimeType:'application/json',buffer:Buffer.from('{"schema_version":999}')});
  await page.locator('[data-theme-status]').filter({hasText:'操作失败'}).waitFor();
  await page.getByRole('button',{name:'外观：跟随系统，点击切换',exact:true}).click();
  await page.getByRole('button',{name:'外观：浅色，点击切换',exact:true}).click();
  await page.reload(); await page.locator('theme-workbench[data-bound="true"]').waitFor();
  check(await page.locator('html').getAttribute('data-appearance') === 'dark', 'appearance preference lost on reload');
  await audit();
  await page.getByRole('button',{name:'外观：深色，点击切换',exact:true}).click();
  console.log('PASS 主题群岛加载、CSS/布局预览、导入导出、启用快照、恢复删除、外观持久化及 360/768/1440px axe/布局审计');
}
