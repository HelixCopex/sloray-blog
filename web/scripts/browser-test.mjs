import { chromium } from 'playwright';
import fs from 'node:fs';
import { createRequire } from 'node:module';
const require = createRequire(import.meta.url);
const axeSource = fs.readFileSync(require.resolve('axe-core/axe.min.js'), 'utf8');
const origin = process.env.SLORAY_BROWSER_URL;
const browser = await chromium.launch({ headless: true });
const context = await browser.newContext();
const page = await context.newPage();
const errors = [];
page.on('pageerror', e => errors.push(e.message));
function check(value, message) { if (!value) throw new Error(message); }
async function audit() {
  await page.evaluate(axeSource);
  const result = await page.evaluate(async () => window.axe.run(document, { runOnly: { type: 'tag', values: ['wcag2a','wcag2aa','wcag21aa'] } }));
  check(result.violations.length === 0, JSON.stringify(result.violations.map(v => ({ id:v.id, targets:v.nodes.map(n => n.target) }))));
  check(await page.locator('h1').count() === 1, 'single h1 required');
}
try {
  await page.goto(origin);
  await page.getByRole('link', { name: '浏览器测试文章', exact: true }).waitFor();
  await audit();
  await page.emulateMedia({colorScheme:'dark'}); await audit();
  await page.emulateMedia({colorScheme:'light'});
  await page.evaluate(() => { window.__navigationProof = 'persistent'; });
  await page.getByRole('link', { name:'浏览器测试文章', exact:true }).click();
  await page.locator('.discussion[data-bound=true]').waitFor();
  check(await page.evaluate(() => window.__navigationProof) === 'persistent', 'article navigation reloaded page');
  await audit();
  check(await page.locator('link[rel=canonical]').getAttribute('href') === 'http://localhost:4321/posts/browser-seed', 'runtime canonical');
  check(await page.locator('script[type="application/ld+json"]').count() === 1, 'JSON-LD missing');
  await page.locator('#guest-name').fill('浏览器读者');
  await page.locator('#comment-body').fill('浏览器提交的评论');
  await page.getByRole('button', {name:'提交评论',exact:true}).click();
  await page.getByText('评论已提交，审核通过后显示。', {exact:true}).waitFor();
  await page.goBack();
  await page.getByRole('link', { name:'浏览器测试文章', exact:true }).waitFor();
  await page.goForward();
  await page.locator('.discussion[data-bound=true]').waitFor();
  check(await page.evaluate(() => window.__navigationProof) === 'persistent', 'history navigation reloaded page');
  await page.getByRole('link', { name:'搜索',exact:true }).click();
  await page.locator('#search-q').fill('浏览器');
  await page.getByRole('button', {name:'搜索',exact:true}).click();
  await page.getByRole('link', {name:'浏览器测试文章',exact:true}).waitFor();
  await audit();
  console.log('PASS 浏览器局部导航、前进后退、评论提交、中文搜索、SEO 与公开页 axe 检查');

  await page.goto(origin + '/login');
  await audit();
  await page.locator('input[name=email]').fill('admin@example.com');
  await page.locator('input[name=password]').fill('a-test-only-password');
  await page.getByRole('button', {name:'登录',exact:true}).click();
  await page.waitForURL('**/admin/posts');
  await page.goto(origin + '/admin/settings');
  await audit();
  await page.goto(origin + '/admin/posts');
  await page.getByRole('link', {name:'新建文章',exact:true}).click();
  await page.locator('#editor[data-bound=true]').waitFor();
  await page.locator('#title').fill('浏览器编辑文章');
  await page.locator('#slug').fill('browser-created');
  await page.locator('#body').fill('# 正文\n浏览器端保存');
  await page.locator('#status').selectOption('published');
  await audit();
  await page.locator('#image-file').setInputFiles({name:'cover.png', mimeType:'image/png', buffer:fs.readFileSync(process.env.SLORAY_BROWSER_IMAGE)});
  await page.getByRole('button', {name:'上传所选图片',exact:true}).click();
  await page.getByRole('button', {name:'设为封面',exact:true}).waitFor({state:'visible',timeout:70000});
  await page.getByRole('button', {name:'设为封面',exact:true}).click();
  check(await page.locator('#cover-media').inputValue(), 'cover was not selected');
  await page.getByRole('button', {name:'保存',exact:true}).click();
  await page.waitForURL(/\/admin\/posts\/[0-9a-f-]+$/);
  await page.locator('#editor[data-bound=true]').waitFor();
  await page.locator('#summary').fill('再次保存');
  await page.getByRole('button', {name:'保存',exact:true}).click();
  await page.getByText('已保存（版本 2）。', {exact:true}).waitFor();
  await page.goto(origin + '/posts/browser-created');
  await page.locator('img.cover').waitFor();
  check(await page.locator('img.cover').evaluate(e => e.complete && e.naturalWidth>0), 'cover did not load');
  await page.locator('.discussion[data-bound=true]').waitFor();
  await page.getByRole('button', {name:'点赞',exact:true}).click();
  await page.getByRole('button', {name:'取消点赞',exact:true}).waitFor();
  await audit();
  await page.goto(origin + '/admin/comments');
  await page.getByRole('button', {name:'通过',exact:true}).click();
  await page.getByText('浏览器提交的评论', {exact:true}).waitFor({state:'hidden'});
  await page.goto(origin + '/posts/browser-seed');
  await page.getByText('浏览器提交的评论', {exact:true}).waitFor();
  await page.goto(origin + '/admin/media');
  await audit();
  page.once('dialog', dialog => dialog.accept());
  await page.getByRole('button', {name:'删除图片',exact:true}).click();
  await page.locator('[data-media-list] li').waitFor({state:'hidden'});
  await page.goto(origin + '/posts/browser-created');
  check(await page.locator('img.cover').count() === 0, 'deleted cover remains');
  check(errors.length === 0, 'browser errors: ' + errors.join('; '));
  console.log('PASS HTML 登录、后台连续保存、跨域直传与封面展示、点赞、审核、删除媒体及管理页 axe 检查');
} finally {
  await browser.close();
}
